/**
 * Get image by index with fallback
 */
export function getBlogImageByIndex(index: number): string {
  return blogImages[index % blogImages.length];
}

/**
 * Get random blog image
 */
export function getRandomBlogImage(): string {
  return blogImages[Math.floor(Math.random() * blogImages.length)];
}

/**
 * Get images by category
 */
export function getBlogImagesByCategory(category: string): string[] {
  const categories: Record<string, number[]> = {
    'academic': [0, 1, 2, 3, 4],
    'writing': [5, 6, 7, 8, 9],
    'graduation': [10, 11, 12, 13, 14],
    'ai': [15, 16, 17, 18, 19],
    'research': [20, 21, 22, 23, 24],
    'productivity': [25, 26, 27, 28, 29],
    'science': [30, 31, 32, 33, 34],
    'creative': [35, 36, 37, 38, 39],
    'education': [40, 41, 42, 43, 44],
    'collaboration': [45, 46, 47, 48, 49],
  };
  
  const indices = categories[category.toLowerCase()] || categories['academic'];
  return indices.map(i => blogImages[i]);
}
